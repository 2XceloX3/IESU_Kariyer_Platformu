/**
 * Taksonomi Terimi Çevirici
 * @param {('titles'|'skills'|'departments'|'industries')} category
 * @param {string} key
 * @param {string} lang ('tr'|'en'|'ar'|'de')
 * @returns {string}
 */
export function translateTaxonomy(category, key, lang = 'tr') {
  if (!TAXONOMY[category] || !TAXONOMY[category][key]) {
    return key || '';
  }
  const term = TAXONOMY[category][key];
  return term[lang] || term.tr || key;
}

export default {
  TAXONOMY,
  translateTaxonomy
};
